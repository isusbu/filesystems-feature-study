#!/bin/bash
# gen_syscall_map.sh - build the LKL -> x86_64 syscall-name mapping from the kernel's own syscall table.
#
# Why: Janus writes its syscall programs with LKL's names, which are the kernel HANDLER names
# (e.g. SYS_newstat, handled by sys_newstat). glibc on x86_64 names the same syscall by its
# x86_64 table name (SYS_stat). The x86_64 table (arch/x86/entry/syscalls/syscall_64.tbl) lists both:
#     4   common   stat   sys_newstat
#  number  abi     x86 name  handler
# So for every handler whose name differs from its x86_64 name, we emit
#     #define SYS_<handler> SYS_<x86 name>        e.g.  #define SYS_newstat SYS_stat
#
# Run on the VM (needs the janus2 container, which has the LKL kernel source):
#     sudo bash gen_syscall_map.sh [WORKDIR]          (default WORKDIR=/srv/janus_replay)
# Writes into WORKDIR:
#     syscall_64.tbl      copy of the table used (for the record)
#     syscall_map.txt     x86_name  handler  number   (all 64-bit syscalls)
#     syscall_compat.h    the generated #defines; lttng_workload.sh compiles with -include syscall_compat.h
set -eu
R=${1:-/srv/janus_replay}
[ -d "$R" ] || { echo "ERROR: workdir $R does not exist"; exit 1; }
C=${C:-janus2}
TBL=${TBL:-/usr/src/janus/lkl/arch/x86/entry/syscalls/syscall_64.tbl}

if [ -n "${TBL_FILE:-}" ]; then cp "$TBL_FILE" "$R/syscall_64.tbl"          # testing / offline use
else docker exec "$C" cat "$TBL" > "$R/syscall_64.tbl" || { echo "ERROR: cannot read $TBL in container $C"; exit 1; }
fi

# x86 name, handler name without the sys_/__x64_sys_ prefix, number  (64-bit ABI: "common" and "64")
awk '!/^#/ && NF>=4 && ($2=="common" || $2=="64") {
       h=$4; sub(/\/ptregs$/,"",h); sub(/^__x64_/,"",h); sub(/^sys_/,"",h); print $3, h, $1 }' "$R/syscall_64.tbl" > "$R/syscall_map.txt"
# (4.17 marks some handlers as "sys_clone/ptregs" - an entry-code detail, not part of the name)

{
  echo "/* generated by gen_syscall_map.sh from $(basename "$TBL")"
  echo "   LKL/Janus syscall names are kernel handler names; map them to the x86_64 names glibc defines. */"
  awk '{ x86[$1]=1; h2x[$2]=$1 }
       END { for (h in h2x) if (!(h in x86)) printf "#define SYS_%s SYS_%s\n", h, h2x[h] }' "$R/syscall_map.txt" | sort
} > "$R/syscall_compat.h"

echo "x86_64 syscalls in table : $(wc -l < "$R/syscall_map.txt")"
echo "names that needed mapping: $(grep -c '^#define' "$R/syscall_compat.h")"
grep '^#define' "$R/syscall_compat.h"
echo "wrote $R/syscall_compat.h"
